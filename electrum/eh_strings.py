# Veneto falls back to Italian for phrases not written yet
FALLBACK = {'vec_IT': 'it_IT'}


def lookup(lang: str, msg: str):
    """Return the Easy Heirs translation of msg, or None."""
    while lang:
        out = STRINGS.get(lang, {}).get(msg)
        if out is not None:
            return out
        lang = FALLBACK.get(lang)
    return None
